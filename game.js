function buildQuestion(count) {
  const correct = rand(state.emojis);
  const wrongPool = state.emojis
    .filter(x => x.name !== correct.name)
    .map(x => x.name);
  const wrong = shuffle(wrongPool).slice(0, count - 1);
  return {
    emoji: correct.emoji,
    answer: correct.name,
    options: shuffle([correct.name, ...wrong])
  };
}

